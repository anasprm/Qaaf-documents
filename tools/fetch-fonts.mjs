// Downloads the two web fonts into src/assets/fonts and generates fonts.css.
// Run once (or when changing weights): node tools/fetch-fonts.mjs
import { mkdir, writeFile, rm } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'assets');
const fontDir = join(root, 'fonts');
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

const requests = [
  {
    url: 'https://fonts.googleapis.com/css2?family=Plus+Jakarta+Sans:wght@400..800&display=swap',
    family: 'Plus Jakarta Sans',
    prefix: 'jakarta',
    subsets: ['latin', 'latin-ext'],
  },
  {
    url: 'https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Arabic:wght@400;700&display=swap',
    family: 'IBM Plex Sans Arabic',
    prefix: 'plex-arabic',
    subsets: ['arabic', 'latin'],
  },
];

await rm(fontDir, { recursive: true, force: true });
await mkdir(fontDir, { recursive: true });
const blocks = [];

for (const request of requests) {
  const css = await fetch(request.url, { headers: { 'User-Agent': UA } }).then((r) => r.text());
  const parts = css.split('/*').slice(1).map((part) => `/*${part}`);

  for (const part of parts) {
    const subset = (part.match(/^\/\* ([\w-]+) \*\//) || [])[1];
    if (!request.subsets.includes(subset)) continue;

    const family = (part.match(/font-family: '([^']+)'/) || [])[1];
    const weight = (part.match(/font-weight: ([^;]+);/) || [])[1].trim().replace(/\s+/g, '-');
    const style = (part.match(/font-style: ([^;]+);/) || [])[1];
    const url = (part.match(/src: url\(([^)]+)\)/) || [])[1];
    const range = (part.match(/unicode-range: ([^;]+);/) || [])[1];
    if (!family || !url) continue;

    const name = `${request.prefix}-${subset}-${weight}.woff2`;
    const font = Buffer.from(await fetch(url, { headers: { 'User-Agent': UA } }).then((r) => r.arrayBuffer()));
    await writeFile(join(fontDir, name), font);

    blocks.push(`@font-face {
  font-family: '${family}';
  font-style: ${style || 'normal'};
  font-weight: ${weight.replace(/-/g, ' ')};
  font-display: swap;
  src: url(fonts/${name}) format('woff2');
  unicode-range: ${range};
}${subset === 'latin' ? '' : ' /* ' + subset + ' */'}`);

    console.log(`${name.padEnd(34)} ${(font.length / 1024).toFixed(1)} KB`);
  }
}

const css = `/* Generated by tools/fetch-fonts.mjs - self-hosted, no third-party requests. */\n${blocks.join('\n\n')}\n`;
const latinBlocks = blocks.filter((b) => b.includes("'Plus Jakarta Sans'"));
const arabicBlocks = blocks.filter((b) => b.includes("'IBM Plex Sans Arabic'"));

await writeFile(
  join(root, 'fonts-en.css'),
  `/* Generated by tools/fetch-fonts.mjs - Latin only. */\n${latinBlocks.join('\n\n')}\n`,
  'utf8',
);
await writeFile(
  join(root, 'fonts-ar.css'),
  `/* Generated by tools/fetch-fonts.mjs - Arabic + Latin. */\n${arabicBlocks.join('\n\n')}\n`,
  'utf8',
);
console.log(`\nfonts-en.css: ${latinBlocks.length} faces, fonts-ar.css: ${arabicBlocks.length} faces`);
